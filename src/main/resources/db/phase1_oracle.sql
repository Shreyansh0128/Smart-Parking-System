
ALTER TABLE PARKING_SLOTS ADD (FLOOR NUMBER(3) DEFAULT 0 NOT NULL);
ALTER TABLE PARKING_SLOTS ADD (SLOT_TYPE VARCHAR2(20) DEFAULT 'CAR' NOT NULL);
ALTER TABLE PARKING_SLOTS ADD CONSTRAINT CK_PARKING_SLOT_STATUS
    CHECK (STATUS IN ('AVAILABLE', 'OCCUPIED', 'RESERVED'));
ALTER TABLE PARKING_SLOTS ADD CONSTRAINT CK_PARKING_SLOT_TYPE
    CHECK (SLOT_TYPE IN ('BIKE', 'CAR', 'EV'));
ALTER TABLE PARKING_SLOTS ADD CONSTRAINT CK_PARKING_SLOT_FLOOR
    CHECK (FLOOR >= 0);

CREATE TABLE PARKING_USERS (
    USER_ID NUMBER PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20) UNIQUE,
    ROLE VARCHAR2(10) DEFAULT 'USER' NOT NULL,
    CONSTRAINT CK_PARKING_USER_ROLE CHECK (ROLE IN ('ADMIN', 'USER'))
);
CREATE SEQUENCE PARKING_USER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE VEHICLES (
    VEHICLE_ID NUMBER PRIMARY KEY,
    USER_ID NUMBER NOT NULL REFERENCES PARKING_USERS(USER_ID),
    REGISTRATION_NUMBER VARCHAR2(20) NOT NULL UNIQUE,
    VEHICLE_TYPE VARCHAR2(10) NOT NULL,
    CONSTRAINT CK_VEHICLE_TYPE CHECK (VEHICLE_TYPE IN ('BIKE', 'CAR', 'EV'))
);
CREATE SEQUENCE VEHICLE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE INDEX IX_VEHICLES_USER ON VEHICLES(USER_ID);

CREATE TABLE PARKING_REQUESTS (
    REQUEST_ID NUMBER PRIMARY KEY,
    VEHICLE_ID NUMBER NOT NULL REFERENCES VEHICLES(VEHICLE_ID),
    REQUESTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    PRIORITY NUMBER(3) DEFAULT 0 NOT NULL,
    REQUEST_STATUS VARCHAR2(15) DEFAULT 'PENDING' NOT NULL,
    SCHEDULING_ALGORITHM VARCHAR2(12),
    CONSTRAINT CK_PARKING_REQUEST_PRIORITY CHECK (PRIORITY BETWEEN 0 AND 100),
    CONSTRAINT CK_PARKING_REQUEST_STATUS CHECK (REQUEST_STATUS IN ('PENDING', 'ALLOCATED', 'REJECTED', 'CANCELLED'))
);
CREATE SEQUENCE PARKING_REQUEST_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE INDEX IX_PARKING_REQUEST_QUEUE ON PARKING_REQUESTS(REQUEST_STATUS, REQUESTED_AT, PRIORITY);
CREATE INDEX IX_PARKING_REQUEST_VEHICLE ON PARKING_REQUESTS(VEHICLE_ID);

CREATE TABLE PARKING_SESSIONS (
    SESSION_ID NUMBER PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL UNIQUE REFERENCES PARKING_REQUESTS(REQUEST_ID),
    VEHICLE_ID NUMBER NOT NULL REFERENCES VEHICLES(VEHICLE_ID),
    SLOT_ID NUMBER NOT NULL REFERENCES PARKING_SLOTS(SLOT_ID),
    STARTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ENDED_AT TIMESTAMP,
    SESSION_STATUS VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT CK_PARKING_SESSION_STATUS CHECK (SESSION_STATUS IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT CK_PARKING_SESSION_TIMES CHECK (ENDED_AT IS NULL OR ENDED_AT >= STARTED_AT)
);
CREATE SEQUENCE PARKING_SESSION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE INDEX IX_PARKING_SESSION_SLOT ON PARKING_SESSIONS(SLOT_ID, SESSION_STATUS);
CREATE INDEX IX_PARKING_SESSION_VEHICLE ON PARKING_SESSIONS(VEHICLE_ID);
CREATE UNIQUE INDEX UX_PARKING_ACTIVE_SLOT ON PARKING_SESSIONS
    (CASE WHEN SESSION_STATUS = 'ACTIVE' THEN SLOT_ID END);

CREATE TABLE ALLOCATION_HISTORY (
    HISTORY_ID NUMBER PRIMARY KEY,
    REQUEST_ID NUMBER NOT NULL REFERENCES PARKING_REQUESTS(REQUEST_ID),
    SLOT_ID NUMBER REFERENCES PARKING_SLOTS(SLOT_ID),
    ALLOCATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    OUTCOME VARCHAR2(15) NOT NULL,
    DETAILS VARCHAR2(500),
    CONSTRAINT CK_ALLOCATION_OUTCOME CHECK (OUTCOME IN ('ALLOCATED', 'NO_SLOT'))
);
CREATE SEQUENCE ALLOCATION_HISTORY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE INDEX IX_ALLOCATION_HISTORY_REQUEST ON ALLOCATION_HISTORY(REQUEST_ID, ALLOCATED_AT);
